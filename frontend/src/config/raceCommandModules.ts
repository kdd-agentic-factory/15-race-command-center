/** Look up a module by route path */
export function moduleByRoute(route: string): RaceModule | undefined {
  return RACE_MODULES.find((m) => m.route === route);
}

/** Group modules by section */
export function modulesBySection(): Record<ModuleSection, RaceModule[]> {
  const groups: Record<ModuleSection, RaceModule[]> = {
    Command: [],
    "Platform Intelligence": [],
    Engineering: [],
    "Track & Competition": [],
  };
  for (const m of RACE_MODULES) {
    groups[m.section].push(m);
  }
  return groups;
}
